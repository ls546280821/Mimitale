export function convoNarrationMode(convo) {
  const mode = convo && convo.narrationMode;
  return Object.prototype.hasOwnProperty.call(NARRATION_MODES, mode) ? mode : DEFAULT_NARRATION_MODE;
}

export function narrationInstruction(convo) {
  return NARRATION_MODES[convoNarrationMode(convo)].text;
}

export function isGmMode(convo) {
  return !!(convo && convo.gmMode === true);
}

/**
 * 「标重点」的规则。
 *
 * 界面上本来就能渲染加粗，但模型不会主动用 —— 结果就是一大段平铺直叙，
 * 读起来累。所以这里明确告诉它可以用哪两种标记、以及**别用太多**
 * （全都强调等于没强调）。
 */
function emphasisRuleText() {
  return (
    `【标重点】\n` +
    `关键的信息（数值、名字、时间地点、重要决定）用 **加粗**；` +
    `真正不能错过的（危险、转折、关键线索、承诺）用 ==高亮==（界面上会显示成带颜色的粗体）。\n` +
    `一轮回复里标一两处就够了 —— 整段都标等于没标。`
  );
}

/**
 * 推进节奏。
 *
 * 这是世界模型最容易出问题的地方：提示词里只要说「推进情节」，
 * 模型就会一口气把整场戏演完 —— 你刚说完「去酒馆玩游戏」，
 * 它已经把酒喝完、游戏赢完、NPC 的反应也全写完了，
 * 甚至替你决定了玩法细节。玩家只剩下看的份。
 *
 * 所以节奏必须显式约束，而且要把「不要替玩家决定」讲清楚。
 *
 * ⚠️ 2026-09-30 重新组织过一遍（step 从 1203 字压到约 770 字），只做两件事：
 *
 *   ① **去掉重复表述**。原来「别把球踢回给玩家 / 别用『等你表态』收尾」这个意思
 *      在四处各说了一遍（「不要做的事」里一条 + 末尾三条 ★）。那是历史上每发现
 *      模型犯一次就补一条堆出来的，逻辑上高度重叠，模型反而更容易糊。现在合并成
 *      末尾那一组 ★。**所有具体症状举例一条没删**（「你想让我做什么」「你要怎么个
 *      ⋯⋯法」「就等你开口」……那些是实战经验，最值钱的部分），删的只是重复的背景
 *      说明和「其余时候 NPC 该做什么就做」这种同义句。
 *
 *   ② **单角色场景不再读「NPC」的文案**。这套节奏本来是给世界模型写的，单角色
 *      扮演一直在复用同一份 —— 宠物/恋人这类场景里，模型每轮要读「在场 NPC 各给
 *      一句话」「NPC 之间的分工由你安排」「最后一句要落在 NPC 身上」，既占篇幅，
 *      又可能把它带偏（凭空造出别的角色）。现在用占位符按场景换词。
 *
 * ⚠️ 2026-09-30 二次修订：
 *   · step 的「一轮只做三件事」拆成「两件 + 写完看情况交还叙述权」——
 *     原来第 3 条「停」是元指令却被列进内容清单，模型常把它当成必须完成的内容。
 *   · 「他刚说的话本身就是在问你」收紧成「玩家明确在等一个回答（提问、征求同意、
 *     要求表态）」，原来那个条件太宽，几乎每轮都成立，和后面 ★ 自相矛盾。
 *   · 单角色模式下 {them} / {other} / {step2} 的残留全部处理掉：
 *     {them} 拿掉的整段由 {moveDefault} 按场景生成，不再出现「你替 TA 拿主意」
 *     这种自我指涉；{other} 对应的整条也做成按场景可空。
 *   · GM 的「让玩家有得选」改成「让玩家知道现在能做什么」——
 *     原来那句话会诱导模型每轮抛问题，正好跟节奏约束打架。
 *   · 「不要主动引入新角色或新事件」加限定词「打断当前互动的」，
 *     否则和「让情节向前走」冲突。
 *
 *  压缩的只是**重复的说法**，不是约束本身。要是实测发现某条又开始犯，把它加回
 *  对应那一组 ★ 里（别再在开头另起一条 —— 那正是这次清掉的东西）。
 *
 * ⚠️ 2026-10-03：step 第 1 条原来写「（2-4 句，最多一段）」。节奏规则只该管**推进多少**，
 *  不该管**写多长** —— 篇幅归角色卡/世界书的【篇幅】和【叙述要求】管。两处并存时，
 *  越靠近生成位置的那条越容易被照抄，结果正文被压成对话记录。所以这里删掉字数与段数，
 *  只留「写清眼下发生了什么」。
 */
