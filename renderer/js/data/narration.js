const DEFAULT_PACE_MODE = 'step';

export function convoPaceMode(convo) {
  const mode = convo && convo.paceMode;
  return Object.prototype.hasOwnProperty.call(PACE_MODES, mode) ? mode : DEFAULT_PACE_MODE;
}

/**
 * 把节奏文案里的场景占位符换成具体的词。
 *
 * 世界模式（isGm）说「NPC」；单角色模式用第二人称「你」—— 这套规则通篇的「你」
 * 都指角色自己（见 roleplayRuleText 开头的「你现在要扮演…」），和 step2 那句
 * 「你给一句话」是同一个口径。**别在单角色模式下点名角色**：既和「第一人称扮演」
 * 打架，也会让模型分不清该用「我」还是用角色名。
 *
 * ⚠️ 单角色模式下还要避开两类句子（下面的整段占位符就是为这个存在的）：
 *    · 「你替 TA 拿主意」—— 自我指涉，模型扮演的就是 TA
 *    · 「别的角色 / 已出场的 NPC」—— 会怂恿它凭空造人
 */
function paceRuleText(convo, isGm) {
  const mode = PACE_MODES[convoPaceMode(convo)] || PACE_MODES[DEFAULT_PACE_MODE];
  const who = isGm ? 'NPC' : '你';

  // 单角色模式：第二人称（和 roleplayRuleText 的「第一人称扮演」对齐），
  // 别再用第三人称点名，模型会分不清该用「我」还是用角色名。
  const step2 = isGm
    ? '在场 NPC 各给一句话或一个动作（每人最多一次）'
    : '你给一句话或一个动作（最多一次）';

  // 单角色没有「多个 NPC 之间分工」这回事 —— 这两条整条不出现
  const multi = isGm ? '  · NPC 之间的先后、分工、争执 —— 由你安排，不要抛给玩家决定\n' : '';
  const multiInline = isGm ? 'NPC 之间的先后和分工由你安排，不要抛给玩家决定；' : '';

  // 「别替玩家了结对峙」在单角色场景里换成不涉及「别的角色」的写法
  const standoffRule = isGm
    ? '  · 不要在对峙里替玩家了结：不让对手突然离场或摊牌，\n' +
      '    不让别的 NPC 接管玩家正在进行的互动\n'
    : '  · 不要替玩家了结冲突：不让对方突然离场或摊牌，不替玩家化解冲突\n';
  const standoffBrisk = isGm
    ? ' · 在对峙里不要替玩家把局面解决掉：不让对手突然离场或摊牌，\n' +
      '   不让别的 NPC 走过来接管玩家正在进行的互动，不替玩家化解冲突；\n'
    : ' · 不要替玩家把冲突解决掉：不让对方突然离场或摊牌，不替玩家化解冲突；\n';

  // 「拿不准该谁动」——单角色模式下「谁」只能是角色自己，改成第二人称
  const moveDefault = isGm
    ? '  · 拿不准该谁动时，默认由 NPC 动 —— 某个 NPC 想干什么、想要什么、\n' +
      '    先做什么，那是你的事，你替他们拿主意，别丢回给玩家。\n'
    : '  · 拿不准接下来该谁动时，默认由你先动 —— 你想干什么、想要什么、\n' +
      '    先做什么，那是你的事，别丢回给玩家。\n';
  const moveDefaultInline = isGm
    ? '默认由 NPC 动 —— 某个 NPC 想干什么，你替他们拿主意'
    : '默认由你先动 —— 你想干什么，自己拿主意';

  // GM 专属：已出场的 NPC 也别硬凑过来（单角色模式下没有第二个角色）
  const noSelfIntro = isGm ? '，已出场的 NPC 也不要自己凑过来改变局面' : '';

  // {multiInline} 在单角色下是空串，而它独占「· 但玩家已经明确要过…」那一行的
  // 第二行 —— 空串会留下一个只有缩进的孤行（模型有时会当成没写完的条目）。
  // 这里把整条尾巴一起收起：没有内容就不留换行。
  const multiInlineLine = isGm
    ? `   ${multiInline}\n`
    : '';

  // 用函数式替换：charName 里万一有 $ 之类的字符，
  // 字符串形式的替换参数会把它当成 $& / $1 这样的特殊序列。
  const out = String(mode.text)
    .replace(/\{multi\}/g, () => multi)
    .replace(/\{multiInlineLine\}/g, () => multiInlineLine)
    .replace(/\{multiInline\}/g, () => multiInline)
    .replace(/\{step2\}/g, () => step2)
    .replace(/\{standoffRule\}/g, () => standoffRule)
    .replace(/\{standoffBrisk\}/g, () => standoffBrisk)
    .replace(/\{moveDefaultInline\}/g, () => moveDefaultInline)
    .replace(/\{moveDefault\}/g, () => moveDefault)
    .replace(/\{noSelfIntro\}/g, () => noSelfIntro)
    .replace(/\{who\}/g, () => who);

  // 节奏段是独立的一段，调用方紧接着拼下一段（【标重点】/「不要提到自己是 AI」）。
  // 文案末尾漏了 \n，两段就会粘成一行 —— 单角色拼出来是「…一律不要出现。【标重点】」，
  // 世界模式是「…一律不要出现。不要提到自己是 AI、语言模型或助手。」。
  // 这在文案里很难一眼看出来（两处分别是「末尾没有 \n」和「中间少一个 \n」），
  // 所以在这里兜住：以后调文案不用记这个账。
  return out.endsWith('\n') ? out : `${out}\n`;
}

export function roleplayRuleText(charName, me, convo) {
  return (
    `【扮演规则】\n` +
    `你现在要扮演「${charName}」。请用「${charName}」的语气、性格和说话习惯回应，` +
    `保持人设前后一致，不要跳出角色，也不要提到自己是 AI、语言模型或助手。` +
    `把对方称作「${me}」。\n` +
    // 人称与描写格式：**卡说了算**。
    // 这里原来硬写「请始终以第一人称…用动作或神态描写时放在括号里」，会和角色卡自己的
    // 写法打架 —— 尤其和文风类预设（「第三人称 + 连续叙述、不要把整段动作括在括号里」）
    // 直接对撞。三方各说各话时，谁赢只取决于注入顺序（预设排在最后，所以是它压住了这条），
    // 那不是设计出来的结果，而是碰巧；用户一旦关掉那条预设，输出就整批退回括号体。
    // 所以改成跟随角色卡：卡写什么人称就用什么人称。卡里没写才退回原来的第一人称。
    `人称和描写格式按上面角色卡里的写法来，不要自己另立一套；` +
    `卡里没写，就用第一人称、把动作和神态描写放在括号里。\n` +
    // 单角色扮演同样要约束节奏：不然你说一句「我们去玩游戏」，
    // 角色会把整场游戏连同胜负一起演完，你只剩看的份
    `${paceRuleText(convo, false)}` +
    emphasisRuleText()
  );
}

/**
 * GM（主持人）规则。
 * 世界模型里模型扮演的是「整个世界和所有 NPC」，主角是玩家。
 * 所以必须明确允许第三人称、多 NPC 视角 —— 这正是角色扮演规则里禁止的事。
 */
export function gmRuleText(charName, me, convo) {
  return (
    `【主持规则】\n` +
    `你是这个世界的叙述者，负责描写环境、扮演其中的所有 NPC，并让情节向前走。\n` +
    `把「${me}」当作故事的主角，用第二人称称呼对方。\n` +
    // 世界模式最常见的崩法不一定是「替玩家做决定」，而是**称呼**：模型写 NPC 的动作，
    // 宾语位置的玩家角色顺手写成第三人称「她/他」，一句话就把主角降格成布景 ——
    // 而它并不觉得自己在代写，所以「不许代写动作/台词」那几条全都被绕过去了。
    // 所以这里单独钉一条形式约束，并且给一组正反对照（示范比抽象描述管用）。
    `★ 称呼铁律：「${me}」一律用第二人称「你」来指代 —— 包括 TA 出现在句子中间、\n` +
    `  作为别人动作的宾语（被拉住、被碰到、被看着）的时候。绝不用「她」「他」「TA」\n` +
    `  或角色的名字来称呼玩家角色。\n` +
    `    ✔ 他把你往灯圈里带了半步，靴尖顶上你的鞋。\n` +
    `    ✗ 他把她往灯圈里带了半步，靴尖顶上她的鞋。\n` +
    // 世界书里往往有**同名角色的第三人称设定**（条目 + GM 名单副本），离生成位置更近，
    // 会把模型拉回「主角也是 NPC」。所以这条要写得明确、不留解释空间。
    `★ 主角只能由玩家驱动：「${me}」是玩家本人操作的角色，不是你的角色。\n` +
    `  绝不描写「${me}」的动作、台词、心理、感受和身体反应，也不让 NPC 替 TA 说话、替 TA 拿主意。\n` +
    `  你只写世界的回应 —— 环境的变化、其他 NPC 的反应，以及玩家已经做出的行为带来的后果。\n` +
    `  轮到 TA 的时候，把场面停在 TA 面前，等玩家自己写下一步，不要替 TA 把这一步走完。\n` +
    `用第三人称描写环境和 NPC；不同 NPC 要有各自的语气和立场，不要让所有人用同一种腔调说话。\n` +
    // 原来写的是「让玩家有得选」——这句会被模型理解成「每轮抛一个问题/给几个选项」，
    // 正好跟下面的节奏约束打架。改成不诱导提问的说法。
    `每次回复都要给出具体的情景，让玩家知道现在能做什么。\n` +
    `${paceRuleText(convo, true)}` +
    `不要提到自己是 AI、语言模型或助手。\n` +
    emphasisRuleText()
  );
}

/**
 * GM 模式压轴的一句：主角不可代写。
 *
 * 为什么要在**最末**再说一遍：【主持规则】里已经交代过，【这个世界的人】抬头里也有，
 * 但那两处都排在**世界书之前** —— 而世界书里往往有同名角色的第三人称设定（条目 + 副本），
 * 离生成位置更近，会把模型拉回「主角也是 NPC」。所以在这里补一句最靠近生成位置的。
 *
 * 这里额外把**称呼**单拎出来说：世界书条目正文通篇是第三人称在写那个同名角色，
 * 模型照抄得最省事，结果 NPC 的动作全对、主角却被写成「她」。
 */
function playerOwnershipReminder(me) {
  return (
    `【主角不可代写】「${me}」是玩家本人操作的角色。称呼 TA 一律用第二人称「你」，` +
    `哪怕 TA 只是别人动作的宾语（写「你」，不写「她」「他」）。\n` +
    `这一轮里 TA 的动作、台词、心理、感受和身体反应，一个字都不要替 TA 写 —— ` +
    `你只写世界和 NPC 对 TA 的反应。`
  );
}

