'use strict';

// ============================================================================
//  views/help.js —— 帮助页里唯一带逻辑的一小块
//
//  帮助页的正文全是静态 HTML（写在 index.html 的 #view-help 里），
//  这一层只负责右上角那颗「复制优化提示词」：
//  把一段整理好的提示词塞进剪贴板，用户拿去粘给任意 AI，
//  再贴上自己写的故事 / 角色卡，就能按帮助页的那份指南逐条被改。
//
//  这段文本和仓库里那份《故事优化提示词.md》是同一份稿子，改一处记得改两处。
// ============================================================================

import { el } from '../core/dom.js';
import { api } from '../core/api.js';
import { showToast } from '../ui/toast.js';

/** 给 AI 的故事 / 角色卡审查提示词（点「复制优化提示词」进剪贴板的就是它） */
export const STORY_REVIEW_PROMPT = `你是一位角色卡 / 故事的编辑，专门帮人把「一眼就想跳过」的角色，改成「AI 每一轮都演得住」的角色。

下面我会给你一份我自己写的东西（角色卡、人设，或者故事片段）。请严格按下面的检查清单逐条过一遍，不要笼统地夸，也不要整个重写 —— 只在必要处给具体的修改。

【先判断】
先分清我给你的内容里，哪些是「会改变角色行为或感受」的，哪些只是装饰。装饰可以不管，问题都出在前者。

【检查清单】
1. 因果：每个性格特点、喜好、习惯，后面有没有「为什么会这样」？只堆形容词的地方，逐条指出，并给出带「因为 / 所以 / 但是」的改写。
2. 想要什么 + 什么挡着：能不能找到一句话说清 TA 想要什么、什么在拦着？如果障碍就是玩家本人，指出来（那样玩家一出现，故事就结束了）。
3. 三个角度：身体 / 世界 / 脑子 —— 缺了哪几个？补上，每样至少一个「作为原因而不是装饰」的具体事实。
4. 摩擦与矛盾：有没有面具和面具后面的东西、互相打架的欲望、要付出代价的忠诚？缺点是不是真的会付出代价？有没有一个能让 TA 开心的乐趣？
5. 细节对概括：把所有「概括式的创伤 / 背景陈述」标出来，改成小而具体、有感官、留个没写完尾巴的画面。
6. 潜台词：凡是把「这个行为意味着什么」讲透的句子，标出来，改成「因」和「行为」并排放着，让读者自己去连。
7. 留白：有没有该钉死却没钉死的地方（会改变行为的那种）？有没有纯装饰、删掉也不影响的句子？
8. 秘密有没有锁：每个秘密是否写明了「TA 会告诉谁、必须先发生什么」？没锁的，补上条件。
9. 别把玩家写进去：凡是钉死「玩家是谁」的句子，全部列出（这会让每场对话都以同一种方式开头）。
10. 声音：角色的说话方式是「被描述」还是「被示范」？只有形容词的话，替我写 2 句 TA 实际说话的样例。
11. 长度：估算 token（约 4 个字符 = 1 token）。超过 2000，指出中间可以砍掉的部分；低于 900，指出该补什么。
12. 开场白：是不是中性的碰面？有没有把「玩家是谁」写死？结尾有没有把话语权交出去（一个直接的问题）？有没有给玩家一个以上的抓手？
13. 逐句筛：这句话改变 TA 做什么、或者 TA 怎么感受吗？不改变的，列成一张「可删」清单。
14. 无效句：有没有「空气仿佛凝固了」「气场填满整个房间」「森林屏住了呼吸」这类没有信息量的氛围句，或者角色自己给自己立传的句子？有就标出来删掉。

【输出格式】
按清单编号分段，每段只写三行：
- 问题：具体是哪一句（引用原文）
- 为什么不行：一句话说清
- 怎么改：直接给出改好的句子，不要「建议再加强一点」这种空话

最后再给两样东西：
① 「最该先改的三处」，按影响从大到小排；
② 一句总评：这份东西现在更像「草料」还是「一栋房子」，离「一栋房子」还差什么。

如果我给的是故事而不是角色卡，就把「角色」理解成「主要人物」，其余照旧。`;

/** 绑定帮助页右上角那颗按钮（页面上的内容不用它管，全是静态 HTML） */
export function initHelp() {
  if (!el.btnCopyHelpPrompt) return;
  el.btnCopyHelpPrompt.addEventListener('click', () => {
    api.copyText(STORY_REVIEW_PROMPT);
    showToast('已复制「故事优化提示词」，粘给 AI 就行', 'ok');
  });
}
